    // Query DB lalu render grid produk sesuai kategori. limit=0 artinya tanpa batas.
    private void tampilkanProduk(String kategori, int limit) {
        kategoriAktif = kategori;
        List<produk> data = produkDAO.getProduk(kategori, limit);
        renderGrid(data);
    }

    // Bersihkan grid lalu isi ulang dengan card sesuai list produk yang diberikan. 
    private void renderGrid(List<produk> data) {
        pnlProdukGrid.removeAll();
        for (produk p : data) {
            pnlProdukGrid.add(buatKartuProduk(p));
        }
        pnlProdukGrid.revalidate();
        pnlProdukGrid.repaint();
    }
    private void loadBannerImage() {
        List<produk> data = produkDAO.getProduk("Semua", 1);
        if (data.isEmpty() || data.get(0).getFotoProduk() == null || data.get(0).getFotoProduk().length == 0) {
            return; // biarkan fallback emoji "\uD83D\uDC55" yang di-set di initComponents
        }
        byte[] foto = data.get(0).getFotoProduk();
        ImageIcon asli = new ImageIcon(foto);
        int w = asli.getIconWidth();
        int h = asli.getIconHeight();
        if (w <= 0 || h <= 0) {
            return;
        }
        int boxW = 90, boxH = 90;
        double rasio = Math.min((double) boxW / w, (double) boxH / h);
        int lebarBaru = (int) (w * rasio);
        int tinggiBaru = (int) (h * rasio);
        Image scaled = asli.getImage().getScaledInstance(lebarBaru, tinggiBaru, Image.SCALE_SMOOTH);
        lblBannerImage.setIcon(new ImageIcon(scaled));
        lblBannerImage.setText(""); // hapus emoji fallback
    }
    
    private ImageIcon muatIcon(String namaFile, int ukuran) {
        java.net.URL url = getClass().getResource("icons/" + namaFile);
        if (url == null) {
            logger.warning("Icon tidak ditemukan: " + namaFile
                    + " (pastikan ada di src/merchorderstudio/icons/)");
            return null;
        }
        ImageIcon asli = new ImageIcon(url);
        Image scaled = asli.getImage().getScaledInstance(ukuran, ukuran, Image.SCALE_SMOOTH);
        return new ImageIcon(scaled);
    }
    
    private void pasangIconTombol(JButton btn, String namaFile, int ukuran) {
        ImageIcon icon = muatIcon(namaFile, ukuran);
        if (icon == null) return;
        btn.setIcon(icon);
        btn.setHorizontalTextPosition(SwingConstants.CENTER);
        btn.setVerticalTextPosition(SwingConstants.BOTTOM);
        btn.setIconTextGap(2);
    }
    
