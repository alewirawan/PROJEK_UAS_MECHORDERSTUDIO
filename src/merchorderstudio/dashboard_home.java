    /**
     * Bangun satu kartu produk: gambar, nama, harga, tombol keranjang.
     * Struktur ini meniru desain ProductCardTemplate.form kamu, tapi dibuat
     * lewat kode karena isinya harus berubah-ubah sesuai data DB.
     */
    private JPanel buatKartuProduk(produk p) {
        JPanel kartu = new JPanel();
        kartu.setLayout(new BorderLayout());
        kartu.setBackground(Color.WHITE);
        kartu.setBorder(BorderFactory.createLineBorder(new Color(230, 230, 230)));
 
        // -- gambar --
        JLabel lblFoto = new JLabel();
        lblFoto.setPreferredSize(new Dimension(150, 110));
        lblFoto.setHorizontalAlignment(SwingConstants.CENTER);
        if (p.getFotoProduk() != null && p.getFotoProduk().length > 0) {
            ImageIcon icon = new ImageIcon(p.getFotoProduk());
            Image scaled = icon.getImage().getScaledInstance(150, 110, Image.SCALE_SMOOTH);
            lblFoto.setIcon(new ImageIcon(scaled));
        } else {
            lblFoto.setText("No Image");
        }
        kartu.add(lblFoto, BorderLayout.NORTH);
 
        // -- info: nama + harga + tombol cart --
        JPanel info = new JPanel(new GridLayout(2, 0));
        JLabel lblNama = new JLabel(p.getNamaProduk());
        info.add(lblNama);
 
        JPanel hargaCart = new JPanel(new BorderLayout());
        JLabel lblHarga = new JLabel(p.getHargaFormatted());
        lblHarga.setFont(new Font("Segoe UI", Font.BOLD, 12));
        lblHarga.setForeground(new Color(255, 107, 0));
        hargaCart.add(lblHarga, BorderLayout.WEST);
 
        JButton btnCartKartu = new JButton("\uD83D\uDED2"); 
        btnCartKartu.setBorderPainted(false);
        btnCartKartu.setContentAreaFilled(false);
        btnCartKartu.addActionListener(e -> {
        boolean sukses = keranjangDAO.tambahItem(sessions.idUser, p.getIdProduk(), 1, null, null, null);
            if (sukses) {
                JOptionPane.showMessageDialog(this, p.getNamaProduk() + " ditambahkan ke keranjang");
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menambahkan ke keranjang, coba lagi.");
            }
        });
        hargaCart.add(btnCartKartu, BorderLayout.EAST);
 
        info.add(hargaCart);
        kartu.add(info, BorderLayout.CENTER);
 
        // -- klik gambar/kartu -> ke detail produk --
        MouseAdapter bukaDetail = new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                // Panggil dengan Frame parent dan mode modal 'true'
                detail_produk frame = new detail_produk((java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(dashboard_home.this), true, p.getIdProduk());
                frame.setLocationRelativeTo(dashboard_home.this); // Muncul di tengah
                frame.setVisible(true);
            }
        };
        lblFoto.addMouseListener(bukaDetail);
        kartu.addMouseListener(bukaDetail);
 
        return kartu;
    }

